    private static void def(String name, String... rows) {
        ICONS.put(name, rows);
    }

    public static boolean has(String name) {
        return ICONS.containsKey(name);
    }

    /** Draws the icon with its top-left corner at (x, y); {@code scale} pixels per icon pixel. */
    public static void draw(Gfx g, String name, int x, int y, int color, int scale) {
        String[] rows = ICONS.get(name);
        if (rows == null) return;
        for (int j = 0; j < rows.length; j++) {
            String row = rows[j];
            int i = 0;
            while (i < row.length()) {
                if (row.charAt(i) != '#') {
                    i++;
                    continue;
                }
                int start = i;
                while (i < row.length() && row.charAt(i) == '#') i++;
                g.fill(x + start * scale, y + j * scale, x + i * scale, y + (j + 1) * scale, color);
            }
        }
    }
